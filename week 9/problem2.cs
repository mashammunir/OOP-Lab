namespace w9p2
{
    public class Person
    {
        protected string name;
        protected string address;

        public Person(string name, string address)
        {
            this.name = name;
            this.address = address;
        }

        public string GetName() { return name; }
        public string GetAddress() { return address; }
        public void SetAddress(string address) { this.address = address; }

        public override string ToString()
        {
            return "Person[name=" + name + ",address=" + address + "]";
        }
    }

    public class Student : Person
    {
        private string program;
        private int year;
        private double fee;

        public Student(string name, string address, string program, int year, double fee) : base(name, address)
        {
            this.program = program;
            this.year = year;
            this.fee = fee;
        }

        public string GetProgram() { return program; }
        public void SetProgram(string program) { this.program = program; }
        public int GetYear() { return year; }
        public void SetYear(int year) { this.year = year; }
        public double GetFee() { return fee; }
        public void SetFee(double fee) { this.fee = fee; }

        public override string ToString()
        {
            return "Student[Person[name=" + name + ",address=" + address + "]," +
                   "program=" + program + ",year=" + year + ",fee=" + fee + "]";
        }
    }

    public class Staff : Person
    {
        private string school;
        private double pay;

        public Staff(string name, string address, string school, double pay) : base(name, address)
        {
            this.school = school;
            this.pay = pay;
        }

        public string GetSchool() { return school; }
        public void SetSchool(string school) { this.school = school; }
        public double GetPay() { return pay; }
        public void SetPay(double pay) { this.pay = pay; }

        public override string ToString()
        {
            return "Staff[Person[name=" + name + ",address=" + address + "]," +
                   "school=" + school + ",pay=" + pay + "]";
        }
    }

    internal class Program
    {
        static void Main(string[] args)
        {
            Student s1 = new Student("John", "123 Main St", "BSCS", 2, 15000.00);
            Student s2 = new Student("Mary", "456 Oak Ave", "BSIT", 3, 18000.00);

